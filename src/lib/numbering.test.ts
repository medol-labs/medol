import assert from 'node:assert/strict';
import test from 'node:test';
import { parseMedol } from './dslParser';
import { modelToCodegenModel, modelToConfig } from './dslToConfig';
import { configToDsl } from './configToDsl';
import { analyzeFieldLineage } from './fieldLineage';
const source = (field = 'code: String generated by Numbers rule "order"', id = 'orderId: UUID id', imported = true) => `${imported ? 'import numbering as Numbers deploy Support' : ''}
context Orders { slice CreateOrder { startsLifecycle command CreateOrder { ${id} ${field} } event OrderCreated { orderId: UUID id code: String } state Created } concept Order { state Created slice CreateOrder } }`;
test('numbering binding exports without losing its capability or rule', () => {
  const parsed = parseMedol(source());
  assert.deepEqual(parsed.diagnostics, []);
  const codegen = modelToCodegenModel(parsed);
  assert.deepEqual(codegen.numbering, {context:'Numbering'});
  const field=codegen.slices.find(s=>s.name==='CreateOrder')!.commands[0].fields.find(f=>f.name==='code')!;
  assert.deepEqual(field.numbering,{capability:'Numbers',rule:'order'});
  const config = modelToConfig(parsed);
  assert.deepEqual(config.slices.find(s => s.title === 'Create Order')!.commands[0].fields.find(f => f.name === 'code')!.numbering, field.numbering);
  assert.throws(() => configToDsl(config), /Legacy config cannot restore numbering/);
  assert(codegen.actors.some(a=>a.name==='NumberingAdministrator'));
  assert(codegen.actors.some(a=>a.name==='NumberingAuditor'));
});
test('builtin numbering has explicit lifecycle and infrastructure event lineage', () => {
  const parsed=parseMedol('import numbering as Numbers deploy Support');
  assert.deepEqual(parsed.diagnostics,[]);
  assert.deepEqual(analyzeFieldLineage(parsed).diagnostics,[]);
  const model=modelToCodegenModel(parsed);
  assert.equal(model.transitions.find(t=>t.command?.name==='SuspendNumberingRule')?.from,'Active');
  assert.equal(model.transitions.find(t=>t.command?.name==='ResumeNumberingRule')?.from,'Suspended');
  assert.equal(model.slices.flatMap(s=>s.commands).length,6);
});
test('numbering rejects unbound, editable, non-string and unidentified allocations', () => {
  for(const text of [source('code: Int generated by Numbers rule "order"'),source('code: String by Numbers rule "order"'),source(undefined,'other: UUID'),source(undefined,undefined,false),source('code: String generated by Numbers rule "bad rule"')]) {
    const parsed=parseMedol(text);
    if(!parsed.diagnostics.length) assert.throws(()=>modelToCodegenModel(parsed), /Number/);
  }
});
test('ordinary context names do not enable numbering; tenant deployment uses control storage', () => {
  assert.equal(modelToCodegenModel(parseMedol('context Numbering {}')).numbering,undefined);
  const model=modelToCodegenModel(parseMedol('import numbering deploy Support\nimport tenant-management deploy Support'));
  assert(model.tenancy?.managementContexts.includes('Numbering'));
});
